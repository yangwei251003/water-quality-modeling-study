H(doc, '6.1 CSTR物理模型推导', level=2, size=13)

P(doc, '清水池（Clear Well）是自来水厂工艺链的最后一个处理单元，主要功能是提供消毒接触时间并调节供水波动。'
   '将清水池近似为连续搅拌槽(CSTR)是环境工程中的标准简化假设，其质量守恒方程为：')

P(doc, 'd(NTU_cw × V) / dt = Q_in(t) × NTU_filt(t) − Q_out(t) × NTU_cw(t)', bold=True)
P(doc, '其中NTU_cw为清水池内浊度（等同于出厂水浊度），V=18,000 m³为池容(18ML)，'
   'Q_in为滤后水入池流量，Q_out为出厂水流量，NTU_filt为滤后水浊度（入池水质）。')

P(doc, '该方程描述了清水池作为"缓冲器"的两重效应：（1）稀释效应——大池容使得突发的高浊度入水被池内'
   '大体积的低浊度水稀释，出口浊度上升速度为Q/V量级；（2）延迟效应——入池水质变化需要一定时间才能'
   '在出口处体现，延迟时间约等于水力停留时间HRT = V/Q（标称HRT约12小时）。')

H(doc, '6.2 RTD停留时间分布分析', level=2, size=13)

P(doc, '停留时间分布(RTD)理论是化学反应工程的核心分析方法之一。对于理想的CSTR，其RTD密度函数为'
   'E(t) = (1/τ̄)·exp(-t/τ̄)，累积分布为F(t) = 1 − exp(-t/τ̄)，其中τ̄=V/Q为平均停留时间。')

P(doc, 'RTD分析的关键结论：对于CSTR，F(τ̄)=1−1/e≈63.2%——即仅有约63%的水分子在水力停留时间τ̄内'
   '离开系统，约37%的"短路"水流在远短于τ̄的时间内通过，同时有部分水流的实际停留时间远长于τ̄。'
   '这一"宽分布"特征意味着仅凭标称HRT来设定控制策略的前馈时间是不够精确的。')

img(doc, 'figS7_rtd_curve.png',
    '图13  清水池停留时间分布：(a)CSTR的RTD密度函数E(t)，τ̄=12h；(b)累积分布F(t)，63.2%的水在12h内离开', w=5.8)

